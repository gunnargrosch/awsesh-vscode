import { existsSync, readFileSync, writeFileSync } from "node:fs"
import path from "node:path"

interface Entry {
  name: string
  version: string
  license: string
  author?: string
}

const root = path.resolve(import.meta.dir, "..")
const packages = new Map<string, Entry>()

function readPackage(dir: string): Record<string, unknown> | undefined {
  const file = path.join(dir, "package.json")
  if (!existsSync(file)) return undefined
  try {
    return JSON.parse(readFileSync(file, "utf8")) as Record<string, unknown>
  } catch {
    return undefined
  }
}

function resolveDir(name: string, fromDir: string): string {
  let current = fromDir
  for (;;) {
    const candidate = path.join(current, "node_modules", name)
    if (existsSync(candidate)) return candidate
    const parent = path.dirname(current)
    if (parent === current) break
    current = parent
  }
  return path.join(root, "node_modules", name)
}

function authorName(author: unknown): string | undefined {
  if (typeof author === "string") return author.replace(/\s*<.*$/, "").replace(/\s*\(.*$/, "").trim()
  if (author && typeof author === "object" && "name" in author && typeof author.name === "string") return author.name
  return undefined
}

function visit(name: string, fromDir: string): void {
  if (packages.has(name)) return
  const dir = resolveDir(name, fromDir)
  const pkg = readPackage(dir)
  if (!pkg) return
  const license = typeof pkg.license === "string" ? pkg.license : "UNKNOWN"
  packages.set(name, {
    name,
    version: typeof pkg.version === "string" ? pkg.version : "",
    license,
    author: authorName(pkg.author),
  })
  const dependencies = (pkg.dependencies as Record<string, string> | undefined) ?? {}
  for (const dependency of Object.keys(dependencies)) visit(dependency, dir)
}

const rootPackage = readPackage(root)
for (const dependency of Object.keys((rootPackage?.dependencies as Record<string, string>) ?? {})) visit(dependency, root)

const entries = [...packages.values()].sort((a, b) => a.name.localeCompare(b.name))
const lines = [
  "# Third-Party Notices",
  "",
  "The packaged extension bundles the following third-party packages. Each is",
  "used under its own license, and the original copyright notice is retained by",
  "its authors.",
  "",
  "Generated by `script/gen-notices.ts` (run with `bun run notices`).",
  "",
]
for (const entry of entries) {
  lines.push(`## ${entry.name}`, `- Version: ${entry.version}`, `- License: ${entry.license}`)
  if (entry.author) lines.push(`- Author: ${entry.author}`)
  lines.push("")
}

writeFileSync(path.join(root, "THIRD-PARTY-NOTICES.md"), lines.join("\n"))
console.log(`Wrote ${entries.length} packages to THIRD-PARTY-NOTICES.md`)
